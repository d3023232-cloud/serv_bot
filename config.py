def _clean_token(raw: str) -> str:
    """Убирает кавычки/пробелы и вытаскивает токен из мусора (на случай, если
    хостинг записал в переменную окружения всю строку вида BOT_TOKEN="123:ABC")."""
    token = raw.strip().strip("'\"").strip()
    if "=" in token:
        # например: BOT_TOKEN=123456:ABC-def (хостинг записал всю строку целиком)
        token = token.split("=", 1)[-1].strip().strip("'\"").strip()
    return token


